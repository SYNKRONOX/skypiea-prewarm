"""Write configs/cold_start.yaml (read by the simulator) from committed E0 runs CSVs.

    python -m experiments.e0_write_cold_start --env kind
    python -m experiments.e0_write_cold_start --env aws      # once the AWS run exists

Every number is computed from results/e0_<env>_runs.csv (sequential) and, if present,
results/e0_<env>_p3_runs.csv (3 tools scaled up at once). Nothing is typed by hand.
Schema: docs/cold_start_schema.md.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd
import yaml

from experiments.e0_cold_start import PHASES

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "configs" / "cold_start.yaml"
SCHEMA_VERSION = 1
STATUS = {
    "kind": "lower bound; replace with AWS (kind pulls from a registry on the same machine)",
    "aws": "measured on AWS (EC2 k3s, images pulled from ECR in the same region)",
}


def _ok(path: Path) -> pd.DataFrame:
    d = pd.read_csv(path)
    return d[d["error"].isna()]


def _stats(s: pd.Series) -> dict:
    return {"median_ms": round(float(s.median()), 1), "p95_ms": round(float(s.quantile(0.95)), 1)}


def mode_block(g: pd.DataFrame, with_phases: bool) -> dict:
    out = {"n": int(len(g)), **_stats(g["total_ms"])}
    if with_phases:
        out["phases_median_ms"] = {p: round(float(g[f"{p}_ms"].median()), 1) for p in PHASES}
    return out


def build(env: str) -> dict:
    seq_csv = ROOT / "results" / f"e0_{env}_runs.csv"
    par_csv = ROOT / "results" / f"e0_{env}_p3_runs.csv"
    seq = _ok(seq_csv)
    tool_map = yaml.safe_load((ROOT / "tools" / "tool_map.yaml").read_text())
    servers = {}
    for name, spec in tool_map["servers"].items():
        g = seq[seq["tool"] == name]
        entry = {"tier": spec["tier"], "classes": list(spec.get("classes", []))}
        for mode in ("cached", "uncached"):
            entry[mode] = mode_block(g[g["mode"] == mode], with_phases=True)
        entry["warm_call_median_ms"] = round(float(g["warm_median_ms"].median()), 1)
        servers[name] = entry
    doc = {
        "schema_version": SCHEMA_VERSION,
        "environment": env,
        "status": STATUS[env],
        "units": "ms",
        "definition": "total = scale request (0 -> 1 replica) -> first successful MCP tool call",
        "source": {
            "experiment": f"e0_{env}",
            "data_commit": str(seq["git_commit"].iloc[0]),
            "report_commit": str(seq["report_commit"].iloc[0])
            if "report_commit" in seq else None,
            "images": str(seq["image"].iloc[0]).rsplit(":", 1)[-1],
            "runs_csv": str(seq_csv.relative_to(ROOT)),
            "run_params": str(seq["run_params"].iloc[0]),
        },
        "fallback": tool_map["fallback"],
        "fallback_patterns": tool_map.get("fallback_patterns", []),
        "servers": servers,
    }
    if par_csv.exists():
        par = _ok(par_csv)
        doc["parallel_3"] = {
            "note": "3 different tools scaled up at the same moment; totals only",
            "runs_csv": str(par_csv.relative_to(ROOT)),
            "run_params": str(par["run_params"].iloc[0]),
            "servers": {
                name: {mode: mode_block(par[(par["tool"] == name) & (par["mode"] == mode)],
                                        with_phases=False)
                       for mode in ("cached", "uncached")}
                for name in tool_map["servers"]
            },
        }
    return doc


HEADER = """\
# Cold-start times per tool server, for the simulator. GENERATED by
#   python -m experiments.e0_write_cold_start --env {env}
# from the E0 runs CSVs; do not edit by hand. Schema: docs/cold_start_schema.md.
# environment: {env} -> {status}
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--env", choices=["kind", "aws"], required=True)
    a = ap.parse_args()
    doc = build(a.env)
    OUT.write_text(HEADER.format(env=a.env, status=STATUS[a.env])
                   + yaml.safe_dump(doc, sort_keys=False, width=100))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(doc['servers'])} servers, env={a.env})")


if __name__ == "__main__":
    main()

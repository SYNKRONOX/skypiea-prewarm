"""Write docs/training_data.md: what each predictor profile was trained and tuned on.

Every count is READ from the pipeline's own split report, data/processed/<source>/report.md
("Splits (by group, seed 0)" table), never typed. The output records the sha256 of each
report and splits.json so a reader with the data can check them. data/processed/ is not
committed (datasets keep their own licences); rebuild it with `make data-all`, then:

    python tools/training_data_table.py            # rewrites docs/training_data.md
    python tools/training_data_table.py --check    # exit 1 if the committed file is stale
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "training_data.md"
# (profile, source, role in that profile)
ROWS = [
    ("support", "tau2_bench", "ranker trained on TRAIN; policy tuned on VAL; evaluated on TEST"),
    ("support", "tau_bench", "listed in the profile's sources, but without timestamps it cannot "
                             "be replayed, so the VAL pick used tau2 only "
                             "(configs/model/profiles.yaml); next-tool accuracy only"),
    ("coding", "tracelab", "ranker trained on TRAIN; policy tuned on VAL; evaluated on TEST"),
    ("coding", "copilot_2026", "policy tuned on VAL (with TraceLab); evaluated on TEST"),
    ("prd (SYNTHETIC)", "synthetic_prd",
     "demo bundle for `make demo`; not used by the Live Console"),
]
NOTES = {
    "tau2_bench": "airline tasks; the users in tau2-bench are LLM-simulated, and tool times come "
                  "from a simulated run (data/README.md)",
    "tau_bench": "has no timestamps",
    "tracelab": "real coding-agent traces with per-call timings (data/README.md)",
    "copilot_2026": "one session per group",
    "synthetic_prd": "generated from the PRD scenario graphs (python -m traces.generate_synthetic)",
}


def splits(report: Path) -> dict[str, tuple[str, str, str]]:
    text = report.read_text()
    m = re.search(r"## Splits[^\n]*\n\s*((?:\|.*\n)+)", text)
    if not m:
        raise SystemExit(f"{report}: no 'Splits' table")
    out = {}
    for line in m.group(1).splitlines():
        cells = [c.strip() for c in line.strip("|").split("|")]
        if cells[0] in ("train", "val", "test"):
            out[cells[0]] = (cells[1], cells[2], cells[3])   # groups, sessions, calls
    if set(out) != {"train", "val", "test"}:
        raise SystemExit(f"{report}: incomplete Splits table")
    return out


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()[:12]


def render(data: Path) -> str:
    lines = [
        "# Training data per predictor profile",
        "",
        "Generated by `python tools/training_data_table.py` from the pipeline split reports in",
        "`data/processed/<source>/report.md` (not committed; `make data-all` rebuilds them). Split",
        "by group with seed 0: 30% of groups to TEST, then 20% of the remaining groups to VAL",
        "(`data/README.md`, step 5). Cells are sessions / calls.",
        "",
        "| Profile | Dataset | Role | TRAIN | VAL | TEST | Note |",
        "|---|---|---|---|---|---|---|",
    ]
    srcs = []
    for profile, src, role in ROWS:
        rep = data / src / "report.md"
        if not rep.exists():
            raise SystemExit(f"missing {rep}: run make data-all "
                             "(and python -m traces.generate_synthetic) first")
        s = splits(rep)
        cell = {k: f"{v[1]} / {v[2]}" for k, v in s.items()}
        lines.append(f"| {profile} | {src} | {role} | {cell['train']} | {cell['val']} | "
                     f"{cell['test']} | {NOTES[src]} |")
        srcs.append(src)
    lines += ["", "Inputs (sha256, first 12 hex digits):", ""]
    for src in srcs:
        rep, spl = data / src / "report.md", data / src / "splits.json"
        lines.append(f"- `{src}`: report.md `{sha(rep)}`, splits.json "
                     f"`{sha(spl) if spl.exists() else 'missing'}`")
    lines += ["",
              "Which bundle uses which source is recorded in each bundle's `MANIFEST.json`",
              "(`source`, `profile`, `synthetic`); the profiles' tuning sources are in",
              "`configs/model/profiles.yaml` and `docs/model.md`",
              "(\"Results in plain language\").", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(ROOT / "data" / "processed"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(Path(a.data))
    if a.check:
        if OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: rerun python tools/training_data_table.py")
            return 1
        print("docs/training_data.md matches the split reports")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Before/after table of the Skye scenario suite (correctness runs).

    python -m agent.suite.compare results/suite/before results/suite/after \
        > docs/SUITE_BEFORE_AFTER.md

Reads the per-run JSON files of both directories (never writes into them). Pass counts per
scenario and model, per-rep pass rates (variance), failure reasons, and what got worse.
"""

from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

from agent.suite.scenarios import SCENARIOS, TITLES


def load(d: Path) -> list[dict]:
    return [json.loads(p.read_text()) for p in sorted(d.glob("*__r*.json"))]


def rate(rows: list[dict]) -> tuple[int, int]:
    return sum(r["pass"] for r in rows), len(rows)


def per_rep(rows: list[dict], model: str) -> list[float]:
    reps = sorted({r["rep"] for r in rows if r["model"] == model})
    out = []
    for k in reps:
        rs = [r for r in rows if r["model"] == model and r["rep"] == k]
        out.append(sum(r["pass"] for r in rs) / len(rs))
    return out


def main(argv: list[str] | None = None) -> int:
    a = argv if argv is not None else sys.argv[1:]
    before, after = load(Path(a[0])), load(Path(a[1]))
    models = sorted({r["model"] for r in before} | {r["model"] for r in after})
    L = ["# Skye scenario suite: before and after (correctness runs)", "",
         "**Correctness runs, not latency results.** Real agent loop (`console/engine.py`) and "
         "real local LLMs (Ollama), tool calls answered in-process by the mock database, no "
         "cluster and no pods; customer turns are scripted per variant; pass = the final "
         "mock-database state equals the expected one (no LLM judge). Suite: "
         "`agent/suite/scenarios.py`; raw runs: `results/suite/before/`, "
         "`results/suite/after/` (generated by `python -m agent.suite.compare`).", "",
         "- **Before**: code `c0089f8` (feat/demo-polish after Phase A), old world (six "
         "fictional airports, USD), 2 reps.",
         "- **After**: code `a8b9693` (feat/demo-realism: synthetic India-centred world and the "
         "STEP 3 guardrails), 3 reps; qwen3:8b with thinking disabled.",
         "- The two worlds have different customers, places and dates, so the scripted lines "
         "differ; the scenario shapes, variants and oracle rules are the same. The guardrails "
         "were developed while looking at this suite's failures (development runs on "
         "llama3.1:8b, not committed): the after numbers can be optimistic for situations the "
         "suite does not cover.", "",
         "## Pass counts per scenario", "",
         "| Scenario | " + " | ".join(f"{m} before | {m} after" for m in models) + " |",
         "|---|" + "---|---|" * len(models)]
    for sc in SCENARIOS + ["all"]:
        cells = []
        for m in models:
            for rows in (before, after):
                rs = [r for r in rows if r["model"] == m and (sc == "all" or r["scenario"] == sc)]
                p, n = rate(rs)
                cells.append(f"{p}/{n}" if n else "–")
        name = "**all**" if sc == "all" else TITLES[sc]
        L.append(f"| {name} | " + " | ".join(cells) + " |")
    L += ["", "## Overall pass rate and variance across reps", "",
          "| Model | Before | Before per rep | After | After per rep (mean ± sd) |",
          "|---|---|---|---|---|"]
    best = None
    for m in models:
        cols = []
        for rows in (before, after):
            rs = [r for r in rows if r["model"] == m]
            p, n = rate(rs)
            pr = per_rep(rows, m)
            sd = f" ± {statistics.stdev(pr):.2f}" if len(pr) > 1 else ""
            cols += [f"{p}/{n} ({p / n:.0%})" if n else "not run",
                     (", ".join(f"{x:.0%}" for x in pr) + (f" (mean {statistics.mean(pr):.0%}"
                                                          f"{sd})" if pr else "")) or "–"]
        rs = [r for r in after if r["model"] == m]
        if rs and (best is None or rate(rs)[0] / rate(rs)[1] > best[1]):
            best = (m, rate(rs)[0] / rate(rs)[1])
        L.append(f"| {m} | " + " | ".join(cols) + " |")
    L += ["", "## What got worse", ""]
    worse = []
    for m in models:
        for sc in SCENARIOS:
            b = [r for r in before if r["model"] == m and r["scenario"] == sc]
            f = [r for r in after if r["model"] == m and r["scenario"] == sc]
            if b and f and rate(f)[0] / rate(f)[1] < rate(b)[0] / rate(b)[1]:
                worse.append(f"- {m}, {TITLES[sc]}: {rate(b)[0]}/{rate(b)[1]} before, "
                             f"{rate(f)[0]}/{rate(f)[1]} after.")
    L += worse or ["- Nothing: no scenario's pass rate went down for a model run both times."]
    L += ["", "## Failure reasons (after)", ""]
    for m in models:
        reasons: dict[str, int] = {}
        for r in after:
            if r["model"] == m and not r["pass"]:
                k = f"{TITLES[r['scenario']]} ({r['variant']}): {r['reason']}"
                reasons[k] = reasons.get(k, 0) + 1
        for k, v in sorted(reasons.items()):
            L.append(f"- {m}: {k} (x{v})")
    L += ["", "## Failure reasons (before)", ""]
    for m in models:
        reasons = {}
        for r in before:
            if r["model"] == m and not r["pass"]:
                k = f"{TITLES[r['scenario']]} ({r['variant']}): {r['reason']}"
                reasons[k] = reasons.get(k, 0) + 1
        for k, v in sorted(reasons.items()):
            L.append(f"- {m}: {k} (x{v})")
    if best:
        L += ["", f"Highest after pass rate: **{best[0]}** ({best[1]:.0%})."]
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

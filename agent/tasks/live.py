class CodeFix(Task):
    def user_prompt(self, i: int) -> str:
        return CODEFIX_SCRIPT[0]

    def scripted(self, i: int) -> list[tuple[str, dict[str, Any]]]:
        return [("search", {"query": "def merge_sort"}),
                ("read_file", {"path": "sortkit/sorting.py"}),
                ("edit_file", {"path": "sortkit/sorting.py",
                               "old": "    result.extend(left[i:])\n",
                               "new": "    result.extend(left[i:])\n"
                                      "    result.extend(right[j:])\n"}),
                ("run_tests", {"selector": "test_sorting"})]

    def gateway_call(self, tool: str, args: dict[str, Any]) -> tuple[str, dict[str, Any]]:
        # timing only: the answer comes from the in-console mock repository
        # (agent/devrepo); no repository content leaves the console
        return self.aliases.get(tool, tool), {}



"""Live-console tasks: an airline-support conversation and a short code fix.

Every tool the LLM sees maps to a tool class that the REAL predictor profile knows, so neither
task needs the SYNTHETIC prd profile:

- airline -> profile ``support`` (bundle lgbm-support-aabdfd2, trained on tau2-bench traces).
  Classes user_lookup, reservation_lookup, flight_search, reservation_modify,
  reservation_cancel and escalate are all in its vocabulary. tools/tool_map.yaml routes the
  five airline classes to ONE server (travel_booking) and escalate to post_comment, so the
  predictor can only change which *servers* are warm: user_lookup, travel_booking, post_comment.
- codefix -> profile ``coding`` (bundle lgbm-coding-af00023; its ranker was trained on
  TraceLab traces, its warm policy tuned on TraceLab + Copilot VAL). Classes search,
  read_file, write_file, run_tests and shell_other are in its vocabulary. The LLM sees the
  friendlier names edit_file (class write_file) and shell (class shell_other).

The checked vocabularies are in configs/live/predictor_vocab.json (generated by
``python -m agent.vocab`` from the predictor image; not typed by hand).

The mock tools return coherent data for the airline flow when called with
``with_reservations`` / ``detail`` (added for this demo; off by default): the same user,
reservation and flight across calls. The coding tools are deterministic mocks over a small
sample repository; an edit is not visible to later calls (each tool runs in its own pod).
"""

from __future__ import annotations

from typing import Any

from agent.tasks import Task, fn

PROFILE_LABELS = {
    "support": "support profile, trained on tau2-bench traces",
    "coding": "coding profile: model trained on TraceLab traces, warm policy tuned on "
              "TraceLab + Copilot",
}

AIRLINE_SYSTEM = """You are an airline customer-support agent. You help customers with their \
flight reservations using tools only; never invent data. Typical flow: identify the customer \
(user_lookup), look up the reservation (reservation_lookup), search alternative flights \
(flight_search), then change (reservation_modify) or cancel (reservation_cancel) the \
reservation once the customer has confirmed. Ask the customer when you need a decision. If \
you cannot help, hand over with transfer_to_human. Keep replies short."""

CODEFIX_SYSTEM = """You are a coding agent working in the `minicalc` repository (Python). Use \
the tools to find code (search), read files (read_file), change files (edit_file), run the \
tests (run_tests) and run shell commands (shell). Work in small steps, run the tests after an \
edit, and report briefly what you changed."""


class Airline(Task):
    def user_prompt(self, i: int) -> str:
        return AIRLINE_SCRIPT[0]

    def scripted(self, i: int) -> list[tuple[str, dict[str, Any]]]:
        return [("user_lookup", {"user_id": "priya_menon_1119"}),
                ("reservation_lookup", {"reservation_id": "R35033531"}),
                ("flight_search", {"origin": "GOI", "destination": "HYD"}),
                ("reservation_modify", {"reservation_id": "R35033531", "flight_no": "SK482"})]


class CodeFix(Task):
    def user_prompt(self, i: int) -> str:
        return CODEFIX_SCRIPT[0]

    def scripted(self, i: int) -> list[tuple[str, dict[str, Any]]]:
        return [("search", {"query": "def mean"}),
                ("read_file", {"path": "src/minicalc/calc.py"}),
                ("edit_file", {"path": "src/minicalc/calc.py", "old": "def mean",
                               "new": "def median(values):\n    ...\n\n\ndef mean"}),
                ("run_tests", {"selector": "test_calc"}),
                ("shell", {"command": "git status"})]


# Autopilot customer scripts: the human side of the conversation, one message per turn.
# Customer priya_menon_1119 owns reservation R35033531 (business, SK216 GOI->HYD, day 45);
# the route has other flights (e.g. SK482 on day 36), so the change is possible.
AIRLINE_SCRIPT = [
    "Hi, this is Priya Menon, user id priya_menon_1119. I need to change my flight on "
    "reservation R35033531 to an earlier day. What are my options?",
    "Please move me to flight SK482 on day 36.",
    "Thanks. That's all.",
]
CODEFIX_SCRIPT = [
    "In the minicalc repo, add a `median(values)` function next to `mean` in "
    "src/minicalc/calc.py. Look at how mean is written first.",
    "Now run the calc tests and tell me if they pass.",
    "Check git status and summarise what changed.",
]

AIRLINE = Airline(
    scenario="airline", name="airline_support", system=AIRLINE_SYSTEM, profile="support",
    tools=[
        fn("user_lookup", "Find a customer by user id or email; returns the profile and "
           "reservation ids.", {"user_id": {"type": "string"}, "email": {"type": "string"}}),
        fn("reservation_lookup", "Get a reservation: flight, route, day, cabin, passengers.",
           {"reservation_id": {"type": "string"}}, ["reservation_id"]),
        fn("flight_search", "Search flights on a route (optionally on one day).",
           {"origin": {"type": "string", "description": "IATA code, e.g. GOI"},
            "destination": {"type": "string"}, "day": {"type": "integer"}},
           ["origin", "destination"]),
        fn("reservation_modify", "Move a reservation to another flight (customer must agree).",
           {"reservation_id": {"type": "string"}, "flight_no": {"type": "string"}},
           ["reservation_id", "flight_no"]),
        fn("reservation_cancel", "Cancel a reservation (customer must agree).",
           {"reservation_id": {"type": "string"}}, ["reservation_id"]),
        fn("transfer_to_human", "Hand the conversation to a human agent.",
           {"body": {"type": "string", "description": "short summary for the human agent"}},
           ["body"])],
    start="user_lookup",
    edges={"user_lookup": {"reservation_lookup", "flight_search", "<end>"},
           "reservation_lookup": {"flight_search", "reservation_cancel", "reservation_lookup",
                                  "transfer_to_human", "<end>"},
           "flight_search": {"flight_search", "reservation_modify", "<end>"},
           "reservation_modify": {"<end>"}, "reservation_cancel": {"<end>"},
           "transfer_to_human": {"<end>"}},
    canonical=["user_lookup", "reservation_lookup", "flight_search", "reservation_modify"],
    aliases={"transfer_to_human": "escalate"},
    fixed_args={"user_lookup": {"with_reservations": True},
                "reservation_lookup": {"action": "lookup", "detail": True},
                "flight_search": {"action": "search"},
                "reservation_modify": {"action": "modify", "detail": True},
                "reservation_cancel": {"action": "cancel", "detail": True},
                "transfer_to_human": {"target": "support/escalations"}})

CODEFIX = CodeFix(
    scenario="codefix", name="code_fix", system=CODEFIX_SYSTEM, profile="coding",
    tools=[
        fn("search", "Find lines in the repository containing a text.",
           {"query": {"type": "string"}}, ["query"]),
        fn("read_file", "Read a repository file (optionally a line range).",
           {"path": {"type": "string"}, "start_line": {"type": "integer"},
            "end_line": {"type": "integer"}}, ["path"]),
        fn("edit_file", "Replace text `old` with `new` in a repository file.",
           {"path": {"type": "string"}, "old": {"type": "string"}, "new": {"type": "string"}},
           ["path", "new"]),
        fn("run_tests", "Run the tests (all, or those matching selector).",
           {"selector": {"type": "string"}}),
        fn("shell", "Run a shell command in the repository (e.g. git status).",
           {"command": {"type": "string"}}, ["command"])],
    start="search",
    edges={t: {"search", "read_file", "edit_file", "run_tests", "shell", "<end>"}
           for t in ("search", "read_file", "edit_file", "run_tests", "shell")},
    canonical=["search", "read_file", "edit_file", "run_tests", "shell"],
    aliases={"edit_file": "write_file", "shell": "shell_other"})

SCRIPTS = {"airline": AIRLINE_SCRIPT, "codefix": CODEFIX_SCRIPT}
